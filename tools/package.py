#!/usr/bin/env python3
"""Collects everything the head unit needs into dist/ID6Term/ after a Momentics / make build:

    libID6Term.so           arm/so-le-v7/libID6Term.so
    ID6Term.manifest        res/
    ID6Term.xml             res/
    ID6Term_ALL_Texts.zip   regenerated by res/make_db.py
    ID6Term_ALL_Images.zip  regenerated by res/make_db.py
    install.sh              to run on the head unit (copies into /opt/hmi/ID5/data/ro/Plugins/ID6Term)
    uninstall.sh

Usage: python3 tools/package.py
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SO = os.path.join(ROOT, "arm", "so-le-v7", "libID6Term.so")
RES = os.path.join(ROOT, "res")
DIST = os.path.join(ROOT, "dist", "ID6Term")

INSTALL_SH = r"""#!/bin/sh
# ID6Term install - run ON THE HEAD UNIT from the directory holding these files (e.g. the USB stick):
#   cd /mnt/umass01200t7/ID6Term && sh install.sh
# Then hold the power button ~30 s to restart the HMI. "Terminal" appears in Media/Radio after Bluetooth audio.
set -e
cd "$(dirname "$0")"
dst=/opt/hmi/ID5/data/ro/Plugins/ID6Term
for f in libID6Term.so ID6Term.manifest ID6Term.xml ID6Term_ALL_Texts.zip ID6Term_ALL_Images.zip; do
    [ -f "$f" ] || { echo "install.sh: $f missing" >&2; exit 1; }
done
mkdir -p "$dst"
cp libID6Term.so ID6Term.manifest ID6Term.xml ID6Term_ALL_Texts.zip ID6Term_ALL_Images.zip "$dst"/
chmod 755 "$dst"/libID6Term.so
mkdir -p /var/opt/id6term 2>/dev/null || true
ls -l "$dst"
echo "installed into $dst - reboot the head unit (hold power ~30 s)"
"""

UNINSTALL_SH = r"""#!/bin/sh
# ID6Term uninstall - run on the head unit, then reboot.
rm -rf /opt/hmi/ID5/data/ro/Plugins/ID6Term
echo "removed /opt/hmi/ID5/data/ro/Plugins/ID6Term (history/config in /var/opt/id6term kept) - reboot the head unit"
"""


def main():
    if not os.path.isfile(SO):
        sys.exit("package.py: %s not found - build the project first (make, or Build in Momentics)" % SO)
    subprocess.check_call([sys.executable, os.path.join(RES, "make_db.py"), RES])
    if os.path.isdir(DIST):
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    shutil.copy2(SO, DIST)
    for f in ("ID6Term.manifest", "ID6Term.xml", "ID6Term_ALL_Texts.zip", "ID6Term_ALL_Images.zip"):
        shutil.copy2(os.path.join(RES, f), DIST)
    for name, body in (("install.sh", INSTALL_SH), ("uninstall.sh", UNINSTALL_SH)):
        with open(os.path.join(DIST, name), "w", newline="\n") as fh:
            fh.write(body)
    print("dist/ID6Term:")
    for f in sorted(os.listdir(DIST)):
        print("  %-24s %8d bytes" % (f, os.path.getsize(os.path.join(DIST, f))))


if __name__ == "__main__":
    main()
